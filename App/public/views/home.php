<script>
    // 1. Advanced Parallax (รองรับ X และ Y)
    // ใช้ requestAnimationFrame เพื่อความลื่นไหลสูงสุด
    let isScrolling = false;

    window.addEventListener('scroll', function () {
        if (!isScrolling) {
            window.requestAnimationFrame(function () {
                updateParallax();
                isScrolling = false;
            });
            isScrolling = true;
        }
    });

    function updateParallax() {
        const parallaxItems = document.querySelectorAll('.parallax-item');
        let scrollPosition = window.pageYOffset;

        parallaxItems.forEach(item => {
            // ดึงค่า Speed X และ Y (ถ้าไม่มีให้เป็น 0)
            let speedX = parseFloat(item.getAttribute('data-speed-x')) || 0;
            let speedY = parseFloat(item.getAttribute('data-speed-y')) || 0;
            let speedOpacity = parseFloat(item.getAttribute('data-speed-opacity')) || 0;

            // คำนวณตำแหน่ง
            let moveX = scrollPosition * speedX;
            let moveY = scrollPosition * speedY;

            // สั่งขยับแบบ 3D (ใช้ GPU ประมวลผล)
            item.style.transform = `translate3d(${moveX}px, ${moveY}px, 0)`;

            // คำนวณความจาง (Opacity) เฉพาะตัวที่มีค่า data-speed-opacity
            if (speedOpacity > 0) {
                // สูตร: 1 - (ระยะเลื่อน * ความเร็ว)
                let newOpacity = 1 - ((scrollPosition / 100) * speedOpacity);

                // จำกัดค่าให้อยู่ระหว่าง 0 ถึง 1 (ไม่ให้ติดลบ)
                if (newOpacity < 0) newOpacity = 0;
                if (newOpacity > 1) newOpacity = 1;

                item.style.opacity = newOpacity;
            }
        });
    }

    // 2. Intersection Observer (ส่วนแสดงผล Fade-in/up เหมือนเดิม)
    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add('reveal-active');
            }
        });
    }, {
        threshold: 0.1
    });

    const hiddenElements = document.querySelectorAll('.reveal-element');
    hiddenElements.forEach((el) => observer.observe(el));
</script>